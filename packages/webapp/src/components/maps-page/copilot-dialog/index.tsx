import React, { use } from 'react';
import { useIntl } from 'react-intl';
import { useMutation, useQueryClient } from '@tanstack/react-query';
import Alert from '@mui/material/Alert';
import MenuItem from '@mui/material/MenuItem';
import TextField from '@mui/material/TextField';
import Typography from '@mui/material/Typography';

import type {
  CopilotMapRequest,
  CopilotMapResult,
  CopilotModel,
  ErrorInfo,
} from '../../../classes/client';
import { ClientContext } from '../../../classes/provider/client-context';
import BaseDialog from '../action-dispatcher/base-dialog';
import LocalityBadge from './locality-badge';
import { CopilotForm } from './styled';

/** Longest prompt the server accepts by default (`app.ai.copilot.max-prompt-length`). */
export const COPILOT_PROMPT_MAX_LENGTH = 2000;

export type CopilotDialogProps = {
  models: CopilotModel[];
  onClose: () => void;
};

/** What the user is told once the map exists: where the answer actually came from. */
const ResultNotice = ({ result }: { result: CopilotMapResult }): React.ReactElement => {
  const intl = useIntl();
  const served = result.servedModel ?? result.model.label;
  const model = result.model.label;

  if (result.routingWarning) {
    const message =
      result.model.locality === 'local'
        ? intl.formatMessage(
            {
              id: 'copilot.result.local-unverified',
              defaultMessage:
                '{model} is declared local, but this could not be verified: the answer came from {served}.',
            },
            { model, served },
          )
        : intl.formatMessage(
            {
              id: 'copilot.result.served-elsewhere',
              defaultMessage:
                '{model} was answered by {served} instead of the expected model. Where your request went could not be verified.',
            },
            { model, served },
          );
    return (
      <Alert
        severity="warning"
        data-testid="copilot-result"
        data-actual-locality={result.actualLocality}
      >
        {message}
      </Alert>
    );
  }

  if (result.actualLocality === 'local') {
    return (
      <Alert severity="success" data-testid="copilot-result" data-actual-locality="local">
        {intl.formatMessage(
          {
            id: 'copilot.result.local',
            defaultMessage: 'Generated locally by {served}: your request stayed in your network.',
          },
          { served },
        )}
      </Alert>
    );
  }

  if (result.actualLocality === 'external') {
    const provider = result.model.provider;
    return (
      <Alert severity="info" data-testid="copilot-result" data-actual-locality="external">
        {provider
          ? intl.formatMessage(
              {
                id: 'copilot.result.external',
                defaultMessage: 'Generated externally by {served}, at {provider}.',
              },
              { served, provider },
            )
          : intl.formatMessage(
              {
                id: 'copilot.result.external-unnamed',
                defaultMessage: 'Generated externally by {served}.',
              },
              { served },
            )}
      </Alert>
    );
  }

  return (
    <Alert severity="info" data-testid="copilot-result" data-actual-locality="unverified">
      {intl.formatMessage(
        {
          id: 'copilot.result.unverified',
          defaultMessage: 'Generated by {served}. Where it ran could not be verified.',
        },
        { served },
      )}
    </Alert>
  );
};

const CopilotDialog = ({ models, onClose }: CopilotDialogProps): React.ReactElement => {
  const client = use(ClientContext);
  const queryClient = useQueryClient();
  const intl = useIntl();
  const [prompt, setPrompt] = React.useState('');
  const [modelId, setModelId] = React.useState<string | undefined>(models[0]?.id);
  const [error, setError] = React.useState<ErrorInfo>();
  const [result, setResult] = React.useState<CopilotMapResult>();

  const model = models.find((m) => m.id === modelId) ?? models[0];

  const mutation = useMutation<CopilotMapResult, ErrorInfo, CopilotMapRequest>({
    mutationFn: (request) => client.createMapWithCopilot(request),
    onSuccess: (created) => {
      setResult(created);
      queryClient.invalidateQueries({ queryKey: ['maps'] });
    },
    onError: (failure) => setError(failure),
  });

  const handleGenerate = (): void => {
    setError(undefined);
    const request: CopilotMapRequest = { prompt, language: intl.locale };
    if (model) {
      request.model = model.id;
    }
    mutation.mutate(request);
  };

  const handleOpenMap = (): void => {
    if (result) {
      window.location.href = `/c/maps/${result.id}/edit`;
    }
  };

  const title = intl.formatMessage({ id: 'copilot.dialog.title', defaultMessage: 'AI Copilot' });

  if (result) {
    return (
      <BaseDialog
        onClose={onClose}
        onSubmit={handleOpenMap}
        title={title}
        submitButton={intl.formatMessage({
          id: 'copilot.dialog.open-map',
          defaultMessage: 'Open the map',
        })}
      >
        <CopilotForm>
          <Typography variant="subtitle1" component="p">
            {result.title}
          </Typography>
          <ResultNotice result={result} />
        </CopilotForm>
      </BaseDialog>
    );
  }

  const external = model?.locality === 'external';
  const generateLabel = !external
    ? intl.formatMessage({ id: 'copilot.dialog.generate', defaultMessage: 'Generate' })
    : model?.provider
      ? intl.formatMessage(
          {
            id: 'copilot.dialog.generate-external',
            defaultMessage: 'Send to {provider} and generate',
          },
          { provider: model.provider },
        )
      : intl.formatMessage({
          id: 'copilot.dialog.generate-external-unnamed',
          defaultMessage: 'Send outside and generate',
        });

  return (
    <BaseDialog
      onClose={onClose}
      onSubmit={handleGenerate}
      error={error}
      isLoading={mutation.isPending}
      title={title}
      description={intl.formatMessage({
        id: 'copilot.dialog.description',
        defaultMessage:
          'Describe the mind map you want. The AI drafts it as a new map that you can edit afterwards.',
      })}
      submitButton={generateLabel}
    >
      <CopilotForm>
        {models.length > 1 && (
          <TextField
            select
            label={intl.formatMessage({ id: 'copilot.dialog.model', defaultMessage: 'Model' })}
            value={model?.id ?? ''}
            onChange={(event) => setModelId(event.target.value)}
            disabled={mutation.isPending}
            fullWidth
          >
            {models.map((m) => (
              <MenuItem key={m.id} value={m.id}>
                {m.label}
              </MenuItem>
            ))}
          </TextField>
        )}
        {model && <LocalityBadge locality={model.locality} provider={model.provider} />}
        <TextField
          name="prompt"
          label={intl.formatMessage({
            id: 'copilot.dialog.prompt',
            defaultMessage: 'What should the map be about?',
          })}
          value={prompt}
          onChange={(event) => setPrompt(event.target.value)}
          required
          multiline
          minRows={4}
          fullWidth
          disabled={mutation.isPending}
          helperText={intl.formatMessage({
            id: 'copilot.dialog.wait-hint',
            defaultMessage: 'Generating can take up to a minute.',
          })}
          slotProps={{ htmlInput: { maxLength: COPILOT_PROMPT_MAX_LENGTH } }}
        />
      </CopilotForm>
    </BaseDialog>
  );
};

export default CopilotDialog;
